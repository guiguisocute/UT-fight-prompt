#!/usr/bin/env python3
"""Recover the Chinese command-button glyphs (战斗 行动 物品 仁慈) of the Chinese
UNDERTALE build from the gameplay recording, so the buttons match the game.

The recording is 640x360 with the 640x480 game scaled by 0.75 into x 80..560.
Button text is a bold pixel font drawn at 2x, so one design pixel = 2 game px =
1.5 video px. Frames where the buttons are on screen are averaged (red channel:
orange and yellow text are both R=255) to beat the compression noise, then for
every glyph the design grid is aligned (sub-pixel search maximising contrast)
and sampled at pixel centres.

    ffmpeg -ss 180 -t 220 -i asset/...mp4 -vf fps=0.25 work/btnf/%03d.png
    .venv/Scripts/python tools/recover_buttons.py     # -> src/btnglyphs.js + work/btn_recovered.png
"""
import glob, json
import numpy as np
from PIL import Image
from scipy import ndimage

BTN_X = [32, 185, 345, 500]  # game px, button left edges (recording)
BTN_Y = 432
LABELS = ['战斗', '行动', '物品', '仁慈']
N = 12  # design size

frames = []
for f in sorted(glob.glob('work/btnf/*.png')):
    a = np.asarray(Image.open(f).convert('RGB'), dtype=np.float32) / 255
    # keep frames where all four button frames are drawn (their orange/yellow border)
    ok = all(a[int(BTN_Y * 0.75) - 2:int(BTN_Y * 0.75) + 3, int(80 + (x + 55) * 0.75), 0].max() > 0.5 for x in BTN_X)
    if ok:
        frames.append(a[..., 0])
print('frames used', len(frames))
V = np.mean(frames, axis=0)


def sample(gx, gy):
    # bilinear sample of the averaged red channel at game coords
    return ndimage.map_coordinates(V, [np.asarray(gy) * 0.75, 80 + np.asarray(gx) * 0.75], order=1)


glyphs = {}
for bi, (bx, lab) in enumerate(zip(BTN_X, LABELS)):
    for ci, ch in enumerate(lab):
        best = None
        # glyph origin search window (game px): text starts ~x+38, advance ~26
        for ox in np.arange(bx + 30 + ci * 24, bx + 46 + ci * 28, 0.25):
            for oy in np.arange(BTN_Y + 4, BTN_Y + 14, 0.25):
                jj, ii = np.mgrid[0:N, 0:N]
                v = sample(ox + ii * 2 + 1, oy + jj * 2 + 1)
                # contrast, and the glyph should fill its box (ink on the edges)
                score = np.abs(v - 0.5).mean() + 0.05 * (v[:, 0].max() + v[:, -1].max() + v[0].max() + v[-1].max())
                if best is None or score > best[0]:
                    best = (score, ox, oy, v)
        _, ox, oy, v = best
        bits = v > 0.5
        glyphs[ch] = [N, [int(sum(1 << (N - 1 - i) for i in range(N) if bits[j, i])) for j in range(N)]]
        print(ch, f'origin ({ox:.2f}, {oy:.2f})')

with open('src/btnglyphs.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/recover_buttons.py from the gameplay recording - do not edit by hand.\n')
    f.write('window.MV_BTN_GLYPHS = ')
    json.dump(glyphs, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')

# preview: recovered glyphs next to the averaged recording
S = 8
out = Image.new('RGB', (len(glyphs) * (N * S + 8), N * S), (40, 40, 40))
for k, (ch, (n, rows)) in enumerate(glyphs.items()):
    for j, r in enumerate(rows):
        for i in range(n):
            if r >> (n - 1 - i) & 1:
                for dy in range(S):
                    for dx in range(S):
                        out.putpixel((k * (N * S + 8) + i * S + dx, j * S + dy), (255, 127, 39))
out.save('work/btn_recovered.png')
crop = Image.fromarray((V * 255).astype('uint8')).crop((int(80 + 24 * 0.75), int(426 * 0.75), int(80 + 620 * 0.75), int(478 * 0.75)))
crop.resize((crop.width * 6, crop.height * 6), Image.NEAREST).save('work/btn_avg.png')
