"""The film's small pictures (bullets, the tiny spiders, the sign, the pet), cut from the sheets by
tools/cut_sheet.py, packed as data URLs under readable names -> src/props_img.js (window.MV_PROPS).

usage: python -I tools/make_props.py
"""
import base64
import io
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
M, G = 'work/muf/props', 'work/rg/p'
F = os.path.join(os.path.dirname(ROOT), 'asgore-mv', 'work', 'cells', 'frisk')
PROPS = {
    # Muffet's attacks (her sheet, "Attacks")
    'donut': f'{M}/00.png', 'muffin': f'{M}/01.png', 'croissant0': f'{M}/02.png', 'croissant1': f'{M}/03.png',
    'spider': f'{M}/04.png', 'teaDrop': f'{M}/05.png',
    # the tiny spiders (two walking frames), the sign spider, the sign unfolding from its pole
    'tiny0': f'{M}/12.png', 'tiny1': f'{M}/14.png', 'signSpider': f'{M}/15.png',
    'sign0': f'{M}/13.png', 'sign1': f'{M}/16.png', 'sign2': f'{M}/17.png', 'sign3': f'{M}/18.png', 'sign4': f'{M}/19.png',
    # the cupcake monster: side view (two frames), rising from below (four frames)
    'pet0': f'{M}/06.png', 'pet1': f'{M}/07.png',
    'petTop0': f'{M}/08.png', 'petTop1': f'{M}/09.png', 'petTop2': f'{M}/10.png', 'petTop3': f'{M}/11.png',
    # the guards' attacks (Hotland sheet, "RG attacks")
    'rgFlame': f'{G}/02.png', 'rgStar': f'{G}/03.png', 'rgWave': f'{G}/06.png',
    # the game's smoke cloud (Mettaton's sheet, cut in ../mtt-mv): src/fx_smoke.js's big puff
    'smoke': os.path.join(os.path.dirname(ROOT), 'mtt-mv', 'work', 'parts', 'smoke.png'),
    # Frisk (asgore-mv's cells of the Frisk sheet): walking, side on (facing left), and the same walk as a
    # silhouette (the game's own dark-room frames)
    **{f'frisk{i}': f'{F}/{24 + i:03d}.png' for i in range(4)},
    **{f'friskSil{i}': f'{F}/{32 + i:03d}.png' for i in range(4)},
}


def url(path):
    b = io.BytesIO()
    Image.open(path).convert('RGBA').save(b, 'PNG')
    return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()


out = {k: url(v) for k, v in PROPS.items()}
with open('src/props_img.js', 'w', encoding='utf-8') as f:
    f.write('// generated by tools/make_props.py from the sprite sheets - do not edit\n')
    f.write('window.MV_PROPS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('src/props_img.js', os.path.getsize('src/props_img.js'), 'bytes,', len(out), 'pictures')
