#!/usr/bin/env python3
"""Bake the dialogue font into src/glyphs.js as bit rows: 8x16 ASCII, 16x16 CJK, plus the
small chat set at 6x12 / 12x12 (from ../mtt-neo-mv/tools/make_font.py). Re-run after adding
Chinese text anywhere in src/.

    .venv/Scripts/python tools/make_font.py [preview.png]

Uses SimSun (Windows) at 16 px: the font carries hand-drawn 16 px bitmap strikes, so FreeType
returns exact 1-bit glyphs and the player never depends on system fonts at runtime.

Without SimSun (e.g. on Linux) the glyphs already in src/glyphs.js are kept exactly as they are and
only characters new to src/ get baked, from WenQuanYi Zen Hei Sharp, whose embedded 12/16 px bitmap
strikes are drawn in the same pixel-Song style. Re-run on Windows to bake every glyph from SimSun.
"""
from PIL import Image, ImageDraw, ImageFont
import glob, json, os, re, sys
import numpy as np

FONT = 'C:/Windows/Fonts/simsun.ttc'
FALLBACK, FALLBACK_INDEX = '/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc', 2
SIMSUN = os.path.exists(FONT)
KEEP16, KEEP12, KEEPBTN = {}, {}, {}
if not SIMSUN:
    if not os.path.exists(FALLBACK):
        sys.exit('Neither SimSun nor WenQuanYi Zen Hei found (apt install fonts-wqy-zenhei).')
    old = open('src/glyphs.js', encoding='utf-8').read()
    grab = lambda name: json.loads(re.search(r'window\.' + name + r' = (\{.*?\});\n', old, re.S).group(1))
    KEEP16, KEEP12, KEEPBTN = grab('MV_GLYPHS'), grab('MV_GLYPHS12'), grab('MV_BTN_GLYPHS')
    print('SimSun not found: keeping the baked glyphs, new characters from WenQuanYi Zen Hei Sharp')
ASCII = ''.join(chr(c) for c in range(32, 127))
CJK = '战斗行动物品仁慈' + '？！。，：…「」—～'
for f in sorted(glob.glob('src/*.js')):
    if f.replace('\\', '/').endswith(('glyphs.js', 'assets.js', 'analysis.js')):
        continue
    CJK += ''.join(re.findall(r'[^\x00-\x7f]', open(f, encoding='utf-8').read()))
CJK = ''.join(ch for ch in dict.fromkeys(CJK) if ch.isprintable() and ch not in '♥★←→↑↓◀▶●♮♭')

font = ImageFont.truetype(FONT, 16) if SIMSUN else ImageFont.truetype(FALLBACK, 16, index=FALLBACK_INDEX)
DY16 = 0 if SIMSUN else 1  # WenQuanYi's 16 px strike sits a pixel higher than SimSun's


def bake(ch, w):
    img = Image.new('1', (w, 16), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = '1'
    d.text((0, DY16), ch, font=font, fill=1)
    rows = []
    for y in range(16):
        v = 0
        for x in range(w):
            if img.getpixel((x, y)):
                v |= 1 << (w - 1 - x)
        rows.append(v)
    return rows


glyphs = {}
for ch in ASCII:
    glyphs[ch] = KEEP16.get(ch) or [8, bake(ch, 8)]
for ch in CJK:
    glyphs[ch] = KEEP16.get(ch) or [16, bake(ch, 16)]

# The small chat font (D.text o.px = 12): SimSun's 12 px bitmap strike, 6x12 ASCII and 12x12 CJK.
# Drawn at y = -1: every glyph in use sits in rows 1-12 of the strike.
font12 = ImageFont.truetype(FONT, 12) if SIMSUN else ImageFont.truetype(FALLBACK, 12, index=FALLBACK_INDEX)


def bake12(ch, w):
    img = Image.new('1', (w, 12), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = '1'
    d.text((0, -1), ch, font=font12, fill=1)
    return [sum(1 << (w - 1 - x) for x in range(w) if img.getpixel((x, y))) for y in range(12)]


glyphs12 = {ch: KEEP12.get(ch) or [6, bake12(ch, 6)] for ch in ASCII}
glyphs12.update({ch: KEEP12.get(ch) or [12, bake12(ch, 12)] for ch in CJK})
# SimSun's 12 px 'm' does not fit the 6 px cell and bakes as an 'n' (muffet_fan read nuffet_fan): hand-drawn, three stems.
FIX12 = {'m': ['......'] * 5 + ['####..'] + ['#.#.#.'] * 4 + ['......'] * 2}
for ch, rows in FIX12.items():
    glyphs12[ch] = [len(rows[0]), [int(r.replace('#', '1').replace('.', '0'), 2) for r in rows]]

BTN_FONT, BTN_N, BTN_TH = 'C:/Windows/Fonts/msyhbd.ttc', 14, 0.42


def bake_btn(ch, n=BTN_N, th=BTN_TH):
    big = n * 24
    f = ImageFont.truetype(BTN_FONT, int(big * 0.98))
    im = Image.new('L', (big, big), 0)
    d = ImageDraw.Draw(im)
    bb = d.textbbox((0, 0), ch, font=f)
    d.text(((big - (bb[2] - bb[0])) / 2 - bb[0], (big - (bb[3] - bb[1])) / 2 - bb[1]), ch, font=f, fill=255)
    a = np.asarray(im, dtype=np.float32).reshape(n, 24, n, 24).mean(axis=(1, 3)) / 255 > th
    return [int(sum(1 << (n - 1 - i) for i in range(n) if a[j, i])) for j in range(n)]


btn = {ch: [BTN_N, bake_btn(ch)] for ch in '战斗行动物品仁慈'} if SIMSUN else KEEPBTN

with open('src/glyphs.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make_font.py (SimSun 16 px and 12 px bitmaps; buttons: YaHei Bold on a 14x14 grid) - do not edit by hand.\n')
    f.write('window.MV_GLYPHS = ')
    json.dump(glyphs, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\nwindow.MV_GLYPHS12 = ')
    json.dump(glyphs12, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\nwindow.MV_BTN_GLYPHS = ')
    json.dump(btn, f, ensure_ascii=False, separators=(',', ':'))
    f.write(';\n')

if len(sys.argv) > 1:
    chars = '战斗行动物品仁慈 * 挡了我的路。 CHARA LV 10 HP 56/56'
    img = Image.new('L', (16 * len(chars), 16), 0)
    x = 0
    for ch in chars:
        w, rows = glyphs.get(ch, [8, [0] * 16])
        for yy, r in enumerate(rows):
            for xx in range(w):
                if r >> (w - 1 - xx) & 1:
                    img.putpixel((x + xx, yy), 255)
        x += w
    img.crop((0, 0, x, 16)).resize((x * 4, 64), Image.NEAREST).save(sys.argv[1])
print(len(glyphs), 'glyphs')
