"""Pack the pictures and sounds into src/assets.js (window.MV_ASSETS = {img, meta, sfx, size}) so the
player works from file:// with no loader (the same scheme as ../Undyne-mv and ../asgore-mv).

* the original battle UI (heart, buttons, HP label, the HUD and damage fonts, the attack bar) and a
  few of its sounds: ../Undyne-mv/src/assets.js (packed there from ../asgore-mv)
* Muffet: the assembled figure off the Spriters Resource sheet (work/slices/muffet/08.png, cut by
  tools/slice_sheet.py), its inside filled with the game's opaque black so the stage behind does not
  show through her

usage: python tools/import_assets.py
"""
import base64
import io
import json
import os

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)


def load_js(path):
    s = open(path, encoding='utf-8').read()
    return json.loads(s[s.index('{'): s.rindex('}') + 1])


def png_uri(im):
    b = io.BytesIO()
    im.save(b, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(b.getvalue()).decode()


def solid(im):
    """the transparent pixels enclosed by the sprite -> opaque black (the outside stays clear)"""
    a = np.array(im.convert('RGBA'))
    op = a[:, :, 3] > 0
    # (closing first: a one-pixel gap in the outline must not let the outside in)
    inside = ndimage.binary_fill_holes(ndimage.binary_closing(op, iterations=1)) & ~op
    a[inside] = [0, 0, 0, 255]
    return Image.fromarray(a)


assets = {'img': {}, 'meta': {}, 'sfx': {}, 'size': {}}
und = load_js('../Undyne-mv/src/assets.js')
UI = ['PlayerHeart', 'UIFight', 'UIAct', 'UIItem', 'UIMercy', 'HP', 'Target', 'TargetChoice', 'Strike', 'BattleFont', 'DamageFont']
for k, v in und['img'].items():
    if k.split('/')[0] in UI:
        assets['img'][k] = v
        if k in und.get('size', {}):
            assets['size'][k] = und['size'][k]
for k in UI:
    if k in und['meta']:
        assets['meta'][k] = und['meta'][k]
for k in ['MenuSelect', 'MenuCursor', 'BattleText', 'Txt1', 'Txt2', 'Hurt', 'Damage', 'Flash', 'Impact', 'Sparkle', 'Bell']:
    if k in und['sfx']:
        assets['sfx'][k] = und['sfx'][k]

# Muffet (placeholder: the assembled "Hurt" frame; the parts and her idle come later)
full = solid(Image.open('work/slices/muffet/08.png'))
assets['img']['muf/full'] = png_uri(full)
assets['size']['muf/full'] = list(full.size)

with open('src/assets.js', 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/import_assets.py - do not edit by hand.\n')
    f.write('window.MV_ASSETS = ' + json.dumps(assets, separators=(',', ':')) + ';\n')
print('img', len(assets['img']), 'meta', len(assets['meta']), 'sfx', len(assets['sfx']), '->', os.path.getsize('src/assets.js'), 'bytes')
